-- แยก "อีเมล" ออกจาก "ชื่อที่แสดง" ก่อนจะเปิดให้ผู้ใช้แก้ชื่อตัวเองได้
--
-- ============================================================================
-- ทำไมต้องมี migration นี้ก่อนช่องเปลี่ยนชื่อใน /settings
-- ============================================================================
-- migration 002 ใส่ค่าตอนสมัครว่า `values (new.id, new.email, 'member')` คือ
-- **เอาอีเมลมาใส่ในช่อง display_name** และตาราง profiles ไม่มีคอลัมน์อีเมลแยกเลย
-- `display_name` จึงเป็นที่เดียวในแอปที่มองเห็นอีเมลของผู้ใช้ได้
--
-- ถ้าเปิดให้แก้ display_name โดยไม่ทำ migration นี้ก่อน จะพังสามที่พร้อมกัน:
--
--   1. /admin/users แสดง `display_name ?? id` เท่านั้น — ผู้ใช้เปลี่ยนชื่อเป็น "ตั้ม"
--      แล้วแอดมินเหลือแต่ uuid ให้เดาว่าใครเป็นใคร
--   2. README บอกวิธีตั้งแอดมินด้วย `where display_name = '<your-email>'` ซึ่งจะ
--      **หาไม่เจอแบบเงียบๆ** (UPDATE 0 rows ไม่ใช่ error)
--   3. activity_log ย้อนชื่อผู้ทำจาก display_name — ผู้ใช้ตั้งชื่อตัวเองเป็นอีเมล
--      ของคนอื่นได้ ทำให้บันทึก "ใครทำอะไร" ชี้ไปผิดคน ข้อนี้หนักที่สุด เพราะ
--      activity_log มีอยู่เพื่อตอบคำถามนั้นคำถามเดียว
--
-- ============================================================================
-- 1. คอลัมน์ใหม่ + เติมค่าย้อนหลัง
-- ============================================================================
alter table public.profiles add column if not exists email text;

-- เติมจาก auth.users ครั้งเดียว แถวที่มีค่าอยู่แล้วไม่ถูกแตะ (รันซ้ำได้)
update public.profiles p
   set email = u.email
  from auth.users u
 where u.id = p.id
   and p.email is distinct from u.email;

create index if not exists profiles_email_idx on public.profiles (email);

-- ============================================================================
-- 2. เขียนอีเมลตอนสมัคร (แทนที่ trigger เดิมของ migration 002)
-- ============================================================================
-- display_name ยังตั้งต้นเป็นอีเมลเหมือนเดิมโดยตั้งใจ — ผู้ใช้ใหม่ที่ยังไม่ตั้งชื่อ
-- ควรมีอะไรให้แอดมินเห็นบ้าง และผู้ใช้เปลี่ยนทีหลังได้เอง
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, display_name, role)
  values (new.id, new.email, new.email, 'member')
  on conflict (id) do nothing;
  return new;
end;
$$;

-- ============================================================================
-- 3. ตามให้ทันเมื่อผู้ใช้เปลี่ยนอีเมล
-- ============================================================================
-- **trigger ตอน INSERT อย่างเดียวไม่พอ** Supabase Auth รองรับการเปลี่ยนอีเมล
-- (updateUser({ email })) ถ้าไม่ตามให้ทัน profiles.email จะค้างอยู่ที่ค่าเก่า
-- แล้วกลายเป็นข้อมูลที่ดู "ทางการ" แต่ผิด ซึ่งแย่กว่าการไม่มีคอลัมน์นี้เลย
-- เพราะแอดมินจะเชื่อมันโดยไม่สงสัย
--
-- ยิงเฉพาะตอนคอลัมน์ email เปลี่ยนจริง (`of email` + `when`) ไม่ใช่ทุกครั้งที่
-- auth.users ถูกอัปเดต — แถวนั้นถูกเขียนทุกครั้งที่มีคนล็อกอิน (last_sign_in_at)
create or replace function public.sync_profile_email()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.profiles set email = new.email where id = new.id;
  return new;
end;
$$;

drop trigger if exists on_auth_user_email_changed on auth.users;
create trigger on_auth_user_email_changed
  after update of email on auth.users
  for each row
  when (old.email is distinct from new.email)
  execute function public.sync_profile_email();

-- ============================================================================
-- 4. สิทธิ์: ไม่ต้องทำอะไรเพิ่ม — และนั่นคือประเด็น
-- ============================================================================
-- migration 019 ถอน UPDATE ระดับตารางแล้วคืนให้เฉพาะ (display_name, settings)
-- **คอลัมน์ที่เพิ่มทีหลังจึงไม่ได้สิทธิ์เขียนโดยอัตโนมัติ** email จึงแก้จากเบราว์เซอร์
-- ไม่ได้ตั้งแต่วินาทีที่มันถูกสร้าง โดยไม่ต้องเขียน revoke อะไรเลย
--
-- นี่คือเหตุผลที่ 019 ต้องมาก่อน 021 ถ้าสลับลำดับ จะมีช่วงที่ผู้ใช้แก้อีเมล
-- ของตัวเองในตาราง profiles ได้ ซึ่งเท่ากับปลอมตัวเป็นคนอื่นในสายตาของแอดมิน
--
-- **ไฟล์นี้ไม่มีคำสั่งเรื่องสิทธิ์เลยสักบรรทัด — ตั้งใจ** สิทธิ์บน profiles เป็นของ
-- migration 019 ที่เดียว มีสองที่สั่งเรื่องเดียวกันเมื่อไร วันหนึ่งจะไม่ตรงกัน
-- **ผลที่ตามมาตอนทำ break check: การรันไฟล์นี้ซ้ำไม่ได้คืนสิทธิ์กลับ**
-- ถ้าเคยรัน `grant update (email) ... to authenticated` เพื่อทดสอบว่าเทสต์จับได้จริง
-- ต้องถอนเองด้วย `revoke update (email) on public.profiles from authenticated;`
-- (เกิดขึ้นจริง 2026-09-08 — เทสต์ตัวที่สามค้างแดงอยู่จนกว่าจะรันคำสั่งนี้)
--
-- SELECT ยังอ่านได้ตามเดิม (policy "read own profile" — เห็นแถวตัวเอง หรือทุกแถวถ้าเป็น admin)

