-- anon ไม่ต้องมีสิทธิ์เขียนอะไรเลยบนตารางนี้
-- ---------------------------------------------------------------------------
-- RLS กันไว้อยู่แล้วเพราะ auth.uid() เป็น null ทำให้ไม่มีแถวไหนเข้าเงื่อนไข
-- แต่สิทธิ์ที่ไม่มีเหตุผลต้องมีก็ไม่ควรค้างไว้ให้ใครมาพึ่งพาผิดๆ ในอนาคต

