-- ปิดช่องยกระดับสิทธิ์ของตัวเอง: ผู้ใช้ที่ล็อกอินแล้วแก้ `profiles.role` ของตัวเองได้
--
-- ============================================================================
-- ช่องโหว่
-- ============================================================================
-- migration 003 สร้าง policy นี้ไว้:
--
--   create policy "update own profile" on profiles
--     for update using (id = auth.uid()) with check (id = auth.uid());
--
-- คอมเมนต์ในไฟล์นั้นเขียนว่า "Role changes are still restricted" ซึ่งถูกเพียงครึ่งเดียว
-- policy ห้ามแก้ **แถวของคนอื่น** ได้จริง แต่ไม่ได้ห้ามแก้ **คอลัมน์ไหน** ในแถวของตัวเอง
-- ทั้ง using และ with check ตรวจแค่ว่าเป็นแถวของตัวเองหรือไม่
--
-- ตรวจกับฐานข้อมูลจริงเมื่อ 2026-09-08 พบว่า anon และ authenticated ได้สิทธิ์ระดับตาราง
-- ครบทุกชนิด (INSERT/SELECT/UPDATE/DELETE/TRUNCATE/REFERENCES/TRIGGER) บน public.profiles
-- ตามค่าตั้งต้นของ Supabase ผลคือผู้ใช้ที่ล็อกอินแล้วยิงคำขอนี้จากเบราว์เซอร์เองได้
-- ด้วย anon key ซึ่งเป็นค่าสาธารณะที่อยู่ใน bundle:
--
--   PATCH /rest/v1/profiles?id=eq.<uuid ของตัวเอง>   { "role": "admin" }
--
-- แล้วได้สิทธิ์ admin ทันที ซึ่งเปิดหน้า /admin/users, การนำเข้าข้อมูล, และการลบข้อมูล
-- ทั้งหมด การกั้น role ที่ชั้นแอปกันได้แค่หน้าจอ ไม่ได้กั้นเส้นทาง REST
--
-- นี่คือความผิดพลาดชนิดเดียวกับที่ migration 016 แก้ไว้กับตาราง candidates:
-- **RLS กรอง "แถว" ส่วน column-level grant กรอง "คอลัมน์" ต้องมีทั้งคู่**
--
-- ============================================================================
-- ทางแก้
-- ============================================================================
-- ถอน UPDATE ระดับตารางทิ้ง แล้วคืนให้เฉพาะสองคอลัมน์ที่ผู้ใช้ต้องแก้เองได้จริง

revoke update on public.profiles from anon, authenticated;

-- display_name — ผู้ใช้ตั้งชื่อที่แสดงของตัวเอง (หน้า /settings)
-- settings    — ข้อความความต้องการที่ใช้บ่อย (หน้า /settings)
--
-- **role ไม่อยู่ในรายการนี้โดยตั้งใจ** และ id ก็ไม่อยู่ (id เป็น FK ไป auth.users
-- การแก้ได้แปลว่าย้ายแถวไปทับบัญชีอื่น)
grant update (display_name, settings) on public.profiles to authenticated;

-- ---------------------------------------------------------------------------
-- ป้องกันเชิงลึก: ถอนสิทธิ์เขียนที่ไม่มีใครใช้
-- ---------------------------------------------------------------------------
-- INSERT  — แถวใน profiles สร้างโดย trigger handle_new_user() ซึ่งเป็น SECURITY DEFINER
--           จึงรันด้วยสิทธิ์ของเจ้าของฟังก์ชัน ไม่ได้ใช้สิทธิ์ของ authenticated
-- DELETE  — ไม่มีเส้นทางในแอปที่ลบ profiles จากเบราว์เซอร์
-- TRUNCATE — **TRUNCATE ไม่อยู่ใต้ RLS เลย** ต่างจาก DELETE ที่ policy กันไว้ได้
--            ตอนนี้ยังยิงผ่าน PostgREST ไม่ได้เพราะ REST รองรับแค่สี่คำสั่งพื้นฐาน
--            แต่สิทธิ์ที่ไม่มีใครต้องใช้ไม่ควรมีอยู่ ถ้าวันหน้ามีเส้นทาง SQL อื่นเปิดขึ้น
--            (เช่น RPC ที่เขียนพลาด) นี่คือสิ่งที่จะทำให้ตารางผู้ใช้ทั้งตารางหายไป
revoke insert, delete, truncate, references, trigger on public.profiles
  from anon, authenticated;

-- SELECT ยังคงไว้ตามเดิม — policy "read own profile" (migration 004) กรองให้แล้วว่า
-- เห็นได้เฉพาะแถวตัวเองหรือถ้าเป็น admin และ getSession() ต้องอ่านแถวตัวเองได้

