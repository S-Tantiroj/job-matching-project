// แต่ผูกกับผู้สมัครแค่ 197 ครั้ง — สกิลส่วนใหญ่เป็นกำพร้า

export type SkillSplit = {
  /** ชื่อที่มีผู้สมัครถืออยู่จริง — ส่งเข้า RPC เป็นตัวกรองได้ */
  usable: string[]
  /** ชื่อที่ไม่มีใครถือ — ไม่ใช้กรอง แต่ยังบอกผู้ใช้ */
  unknown: string[]
}

/**
 * @param chips  ชิปสกิลที่จะใช้กรอง
 * @param known  ชื่อสกิลที่**มีผู้สมัครถืออยู่จริง** (ตัวพิมพ์แบบไหนก็ได้)
 *
 * **เทียบแบบไม่สนตัวพิมพ์ แต่คืนค่าตามที่ผู้ใช้เห็น** — RPC ก็ `lower()` ทั้งสองข้าง
 * อยู่แล้ว การคืนรูปเดิมทำให้ข้อความที่แสดงตรงกับชิปบนจอ ไม่ใช่รูปที่เก็บในฐาน
 */
export function splitKnownSkills(chips: string[], known: string[]): SkillSplit {
  const set = new Set(known.map((k) => k.trim().toLowerCase()).filter(Boolean))
  const usable: string[] = []
  const unknown: string[] = []
  const seen = new Set<string>()

  for (const raw of chips) {
    const chip = typeof raw === 'string' ? raw.trim() : ''
    if (!chip) continue
    const key = chip.toLowerCase()
    if (seen.has(key)) continue
    seen.add(key)
    ;(set.has(key) ? usable : unknown).push(chip)
  }
  return { usable, unknown }
}

/**
 * ข้อความบอกผู้ใช้ว่าชิปไหนไม่ได้ถูกใช้กรอง
 *
 * **ต้องบอกว่ายัง "ใช้จัดอันดับ" อยู่** — คำเหล่านั้นอยู่ในข้อความที่ถูก embed
 * จึงยังมีผลต่อลำดับ แค่ไม่ได้ตัดใครทิ้ง ถ้าเขียนแค่ "ไม่ถูกใช้" ผู้ใช้จะเข้าใจว่า
 * พิมพ์ไปเปล่าๆ แล้วเลิกใช้ช่องนั้น
 */
export function unusedSkillNotice(unknown: string[]): string {
  if (!unknown.length) return ''
  return `ไม่มีผู้สมัครคนไหนมีสกิล ${unknown.join(' · ')} จึงไม่ถูกใช้เป็นตัวกรอง (ยังใช้จัดอันดับอยู่)`
}
